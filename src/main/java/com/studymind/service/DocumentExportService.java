package com.studymind.service;

import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.font.PDType1Font;
import org.apache.pdfbox.pdmodel.font.Standard14Fonts;
import org.apache.poi.ss.usermodel.*;
import org.apache.poi.xssf.usermodel.XSSFWorkbook;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.util.ArrayList;
import java.util.List;

/**
 * DocumentExportService generates downloadable study files:
 * 1. Formatted Study Notes PDF using Apache PDFBox.
 * 2. Structured Study Material Excel (.xlsx) using Apache POI.
 */
@Service
public class DocumentExportService {

    private static final Logger logger = LoggerFactory.getLogger(DocumentExportService.class);

    /**
     * Generates a downloadable PDF file containing formatted study notes.
     */
    public byte[] generateNotesPdf(String title, String content) throws IOException {
        try (PDDocument document = new PDDocument()) {
            PDPage page = new PDPage(PDRectangle.A4);
            document.addPage(page);

            PDType1Font titleFont = new PDType1Font(Standard14Fonts.FontName.HELVETICA_BOLD);
            PDType1Font bodyFont = new PDType1Font(Standard14Fonts.FontName.HELVETICA);

            float margin = 50;
            float yStart = page.getMediaBox().getHeight() - margin;
            float yPosition = yStart;
            float leading = 16;
            float width = page.getMediaBox().getWidth() - (2 * margin);

            PDPageContentStream contentStream = new PDPageContentStream(document, page);

            // Title Header
            contentStream.beginText();
            contentStream.setFont(titleFont, 16);
            contentStream.newLineAtOffset(margin, yPosition);
            contentStream.showText(sanitizeText(title != null ? title : "StudyMind AI - Generated Notes"));
            contentStream.endText();
            yPosition -= 26;

            // Subtitle
            contentStream.beginText();
            contentStream.setFont(bodyFont, 9);
            contentStream.newLineAtOffset(margin, yPosition);
            contentStream.showText("Generated by StudyMind AI Tutor & Study Companion");
            contentStream.endText();
            yPosition -= 20;

            // Horizontal Separator Line
            contentStream.setLineWidth(1f);
            contentStream.moveTo(margin, yPosition);
            contentStream.lineTo(margin + width, yPosition);
            contentStream.stroke();
            yPosition -= 20;

            // Content Body text
            contentStream.beginText();
            contentStream.setFont(bodyFont, 10);
            contentStream.newLineAtOffset(margin, yPosition);

            String[] rawLines = content.split("\\r?\\n");
            for (String rawLine : rawLines) {
                List<String> wrappedLines = wrapText(sanitizeText(rawLine), bodyFont, 10, width);
                for (String line : wrappedLines) {
                    if (yPosition < margin + 40) {
                        contentStream.endText();
                        contentStream.close();

                        // Add new page
                        page = new PDPage(PDRectangle.A4);
                        document.addPage(page);
                        contentStream = new PDPageContentStream(document, page);
                        yPosition = page.getMediaBox().getHeight() - margin;
                        contentStream.beginText();
                        contentStream.setFont(bodyFont, 10);
                        contentStream.newLineAtOffset(margin, yPosition);
                    }
                    contentStream.showText(line);
                    contentStream.newLineAtOffset(0, -leading);
                    yPosition -= leading;
                }
            }

            contentStream.endText();
            contentStream.close();

            ByteArrayOutputStream baos = new ByteArrayOutputStream();
            document.save(baos);
            return baos.toByteArray();
        }
    }

    /**
     * Generates a structured Excel workbook (.xlsx) for Study Topics / Flashcards / MCQs.
     */
    public byte[] generateStudyExcel(String topic, String notesContent) throws IOException {
        try (Workbook workbook = new XSSFWorkbook()) {
            Sheet sheet = workbook.createSheet("Study Revision Sheet");

            // Header Style
            CellStyle headerStyle = workbook.createCellStyle();
            org.apache.poi.ss.usermodel.Font headerFont = workbook.createFont();
            headerFont.setBold(true);
            headerFont.setColor(IndexedColors.WHITE.getIndex());
            headerStyle.setFont(headerFont);
            headerStyle.setFillForegroundColor(IndexedColors.BLACK.getIndex());
            headerStyle.setFillPattern(FillPatternType.SOLID_FOREGROUND);

            // Row 0: Headers
            Row headerRow = sheet.createRow(0);
            String[] headers = {"Item #", "Study Note / Concept / Question", "Category"};
            for (int i = 0; i < headers.length; i++) {
                Cell cell = headerRow.createCell(i);
                cell.setCellValue(headers[i]);
                cell.setCellStyle(headerStyle);
            }

            // Data rows
            String[] lines = notesContent.split("\\r?\\n");
            int rowIndex = 1;
            for (String line : lines) {
                String clean = line.trim();
                if (clean.isEmpty()) continue;

                Row row = sheet.createRow(rowIndex);
                row.createCell(0).setCellValue(rowIndex);
                row.createCell(1).setCellValue(clean);
                row.createCell(2).setCellValue(clean.startsWith("Q") ? "Quiz" : (clean.startsWith("CARD") ? "Flashcard" : "Revision Point"));
                rowIndex++;
            }

            sheet.autoSizeColumn(0);
            sheet.setColumnWidth(1, 22000);
            sheet.autoSizeColumn(2);

            ByteArrayOutputStream baos = new ByteArrayOutputStream();
            workbook.write(baos);
            return baos.toByteArray();
        }
    }

    private List<String> wrapText(String text, PDType1Font font, float fontSize, float maxWidth) throws IOException {
        List<String> result = new ArrayList<>();
        if (text.isEmpty()) {
            result.add("");
            return result;
        }

        String[] words = text.split(" ");
        StringBuilder currentLine = new StringBuilder();

        for (String word : words) {
            String test = currentLine.isEmpty() ? word : currentLine + " " + word;
            float strWidth = font.getStringWidth(test) / 1000 * fontSize;
            if (strWidth > maxWidth) {
                if (!currentLine.isEmpty()) {
                    result.add(currentLine.toString());
                    currentLine = new StringBuilder(word);
                } else {
                    result.add(test);
                    currentLine = new StringBuilder();
                }
            } else {
                currentLine = new StringBuilder(test);
            }
        }
        if (!currentLine.isEmpty()) {
            result.add(currentLine.toString());
        }
        return result;
    }

    private String sanitizeText(String text) {
        if (text == null) return "";
        // Replace unsupported characters for standard Type1 font
        return text.replaceAll("[^\\x20-\\x7E]", " ").trim();
    }
}
